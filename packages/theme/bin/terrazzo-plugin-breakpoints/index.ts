import assert from 'node:assert';
import type { Plugin } from '@terrazzo/parser';

interface BreakpointsPluginOptions {
	/**
	 * Output filename for the generated TypeScript breakpoint map.
	 */
	tsFilename?: string;
	/**
	 * Output filename for the generated CSS custom media queries.
	 */
	cssFilename?: string;
}

interface BreakpointEntry {
	name: string;
	value: number;
	unit: string;
}

/**
 * Generates typed TypeScript breakpoint constants and CSS `@custom-media`
 * declarations from `wpds-breakpoint.*` DTCG dimension tokens so JS hooks and
 * CSS media queries stay aligned with a single token source.
 *
 * @param options             Plugin options.
 * @param options.tsFilename  Output path for generated TypeScript module.
 * @param options.cssFilename Output path for generated CSS custom media rules.
 */
export default function pluginBreakpoints( {
	tsFilename = 'src/prebuilt/ts/breakpoints.ts',
	cssFilename = 'prebuilt/css/breakpoints.css',
}: BreakpointsPluginOptions = {} ): Plugin {
	const breakpoints: BreakpointEntry[] = [];

	return {
		name: '@wordpress/terrazzo-plugin-breakpoints',
		async transform( { tokens } ) {
			for ( const [ id, token ] of Object.entries( tokens ) ) {
				const match = /^wpds-breakpoint\.([^.]+)$/.exec( id );
				if ( ! match ) {
					continue;
				}

				assert(
					token.$type === 'dimension',
					`Expected breakpoint token "${ id }" to have $type "dimension".`
				);

				const { value, unit } = token.$value as {
					value: number;
					unit: string;
				};

				assert(
					unit === 'px',
					`Expected breakpoint token "${ id }" to use "px" unit, received "${ unit }".`
				);

				breakpoints.push( {
					name: match[ 1 ],
					value,
					unit,
				} );
			}
		},
		async build( { outputFile } ) {
			assert(
				breakpoints.length > 0,
				'No wpds-breakpoint.* tokens were found.'
			);

			const sorted = [ ...breakpoints ].sort(
				( a, b ) => a.value - b.value
			);

			const tsEntries = sorted
				.map(
					( { name, value } ) =>
						`\t${ JSON.stringify( name ) }: ${ value },`
				)
				.join( '\n' );

			const tsOrder = sorted
				.map( ( { name } ) => JSON.stringify( name ) )
				.join( ', ' );

			outputFile(
				tsFilename,
				[
					'/*',
					' * This file is generated by the @wordpress/terrazzo-plugin-breakpoints plugin.',
					' * Do not edit this file directly.',
					' */',
					'',
					"import type { Breakpoint } from './token-types.ts';",
					'',
					'/**',
					' * Minimum width thresholds (in pixels) for each WPDS breakpoint token.',
					' */',
					'export const BREAKPOINTS: Readonly< Record< Breakpoint, number > > = {',
					tsEntries,
					'};',
					'',
					'/**',
					' * Breakpoint names ordered ascending by minimum width.',
					' */',
					`export const BREAKPOINT_ORDER: readonly Breakpoint[] = [ ${ tsOrder } ];`,
					'',
				].join( '\n' )
			);

			const cssRules = sorted
				.map(
					( { name, value, unit } ) =>
						`@custom-media --wpds-breakpoint-${ name } (min-width: ${ value }${ unit });`
				)
				.join( '\n' );

			outputFile(
				cssFilename,
				[
					'/*',
					' * This file is generated by the @wordpress/terrazzo-plugin-breakpoints plugin.',
					' * Do not edit this file directly.',
					' */',
					'',
					cssRules,
					'',
				].join( '\n' )
			);
		},
	};
}
